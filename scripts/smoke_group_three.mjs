import { chromium } from "playwright";
import assert from "node:assert/strict";
const root=process.env.G3_SMOKE_URL || "http://127.0.0.1:3178/";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
const errors=[],bad=[];
page.on("pageerror",e=>errors.push(e.message));
page.on("response",r=>{if(r.status()>=400&&/\\.(js|json|mp3)/.test(r.url()))bad.push(r.status()+" "+r.url())});
try{
 await page.goto(root,{waitUntil:"networkidle",timeout:30000});
 await page.locator('[data-view="group-three"]').click();
 await page.locator("#g3PatternList .g3PatternChip").first().waitFor({timeout:15000});
 assert.equal(await page.locator("#g3PatternList .g3PatternChip").count(),18);
 assert.equal((await page.locator("#g3Title").innerText()).trim(),"I can");
 assert.equal(await page.locator("#g3SceneSteps button").count(),4);
 assert.equal((await page.locator("#g3MainEnglish").innerText()).trim(),"I can speak English.");
 assert.equal(await page.locator("#g3ChapterTabs button").count(),3);
 assert.equal(await page.locator("#g3ChapterLines button").count(),6);
 assert.match(await page.locator("#g3Visual").innerText(),/مشهد توضيحي مؤقت/);
 assert.equal(await page.locator("#g3Visual img").count(),0);
 const sentence="I can speak English.";
 await page.locator("#g3QuizOptions button").filter({hasText:sentence}).click();
 assert.match(await page.locator("#g3QuizFeedback").innerText(),/أحسنت/);
 const words=sentence.split(/\s+/);
 for(let i=0;i<words.length;i++) await page.locator('[data-g3-token="'+i+'"]').click();
 assert.match(await page.locator("#g3Progress").innerText(),/1 \/ 72/);
 await page.locator("#g3ChapterTabs [data-g3-chapter='1']").click();
 assert.match(await page.locator("#g3ChapterLines").innerText(),/I need to finish/);
 await page.locator("#g3StoryToggle").click();
 assert.equal(await page.locator("#g3StoryList .g3StoryRow").count(),2);
 await page.locator('[data-g3-pattern="17"]').first().click();
 assert.equal((await page.locator("#g3Title").innerText()).trim(),"Would you like to");
 assert.equal(await page.locator("#g3SceneSteps button").count(),4);
 assert.equal(await page.locator("#g3ChapterTabs button").count(),3);
 assert.equal(await page.locator("#g3Visual img").count(),0);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2);
 assert.equal(overflow,false,"Mobile horizontal overflow");
 await page.reload({waitUntil:"networkidle"});
 await page.locator('[data-view="group-three"]').click();
 await page.locator("#g3PatternList .g3PatternChip").first().waitFor();
 assert.match(await page.locator("#g3Progress").innerText(),/1 \/ 72/);
 await page.locator('[data-view="group-two"]').click();
 await page.locator("#g2PatternList .g2PatternChip").first().waitFor();
 assert.equal(await page.locator("#g2PatternList .g2PatternChip").count(),18);
 await page.locator('[data-view="group-one"]').click();
 await page.locator("#g1PatternList .g1PatternChip").first().waitFor();
 assert.equal(await page.locator("#g1PatternList .g1PatternChip").count(),18);
 assert.deepEqual(errors,[]);
 assert.deepEqual(bad,[]);
 console.log("OK mobile smoke: 18 group-three patterns, quiz, word builder, 3 chapter stories, progress, zero broken assets; groups one and two intact");
}finally{await browser.close()}
