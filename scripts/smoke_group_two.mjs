import { chromium } from "playwright";
import assert from "node:assert/strict";
const root=process.env.G2_SMOKE_URL || "http://127.0.0.1:3178/";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
const errors=[],bad=[];
page.on("pageerror",e=>errors.push(e.message));
page.on("response",r=>{if(r.status()>=400&&/\\.(js|json|mp3)/.test(r.url()))bad.push(r.status()+" "+r.url())});
try{
 await page.goto(root,{waitUntil:"networkidle",timeout:30000});
 await page.locator('[data-view="group-two"]').click();
 await page.locator("#g2PatternList .g2PatternChip").first().waitFor({timeout:15000});
 assert.equal(await page.locator("#g2PatternList .g2PatternChip").count(),18);
 assert.equal((await page.locator("#g2Title").innerText()).trim(),"I wake up");
 assert.equal(await page.locator("#g2SceneSteps button").count(),4);
 assert.equal((await page.locator("#g2MainEnglish").innerText()).trim(),"I wake up at six.");
 assert.equal(await page.locator("#g2ChapterTabs button").count(),3);
 assert.equal(await page.locator("#g2ChapterLines button").count(),6);
 assert.match(await page.locator("#g2Visual").innerText(),/مشهد توضيحي مؤقت/);
 assert.equal(await page.locator("#g2Visual img").count(),0);
 const sentence="I wake up at six.";
 await page.locator("#g2QuizOptions button").filter({hasText:sentence}).click();
 assert.match(await page.locator("#g2QuizFeedback").innerText(),/أحسنت/);
 const words=sentence.split(/\s+/);
 for(let i=0;i<words.length;i++) await page.locator('[data-g2-token="'+i+'"]').click();
 assert.match(await page.locator("#g2Progress").innerText(),/1 \/ 72/);
 await page.locator("#g2ChapterTabs [data-g2-chapter='1']").click();
 assert.match(await page.locator("#g2ChapterLines").innerText(),/I go to school/);
 await page.locator("#g2StoryToggle").click();
 assert.equal(await page.locator("#g2StoryList .g2StoryRow").count(),2);
 await page.locator('[data-g2-pattern="17"]').first().click();
 assert.equal((await page.locator("#g2Title").innerText()).trim(),"On weekends");
 assert.equal(await page.locator("#g2SceneSteps button").count(),4);
 assert.equal(await page.locator("#g2ChapterTabs button").count(),3);
 assert.equal(await page.locator("#g2Visual img").count(),0);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2);
 assert.equal(overflow,false,"Mobile horizontal overflow");
 await page.reload({waitUntil:"networkidle"});
 await page.locator('[data-view="group-two"]').click();
 await page.locator("#g2PatternList .g2PatternChip").first().waitFor();
 assert.match(await page.locator("#g2Progress").innerText(),/1 \/ 72/);
 await page.locator('[data-view="group-one"]').click();
 await page.locator("#g1PatternList .g1PatternChip").first().waitFor();
 assert.equal(await page.locator("#g1PatternList .g1PatternChip").count(),18);
 assert.deepEqual(errors,[]);
 assert.deepEqual(bad,[]);
 console.log("OK mobile smoke: 18 group-two patterns, quiz, word builder, 3 chapter stories, progress, zero broken assets; group one intact");
}finally{await browser.close()}
